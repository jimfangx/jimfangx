#!/usr/bin/env bash

# Bootstrap a Linux machine with my shell setup. No sudo needed.
# Safe to re-run: steps that are already done are skipped.
#
#   ./linux-bootstrap.sh       (from a clone of github.com/jimfangx/jimfangx)
#   curl -fsSL https://raw.githubusercontent.com/jimfangx/jimfangx/main/linux-bootstrap.sh | bash
#
# Requires preinstalled (installing these needs sudo): zsh, git, curl, tar, ssh-keygen,
# and tmux >= 3.3 for tmux-config (skipped with a warning if missing)

set -euo pipefail

REPO_RAW="https://raw.githubusercontent.com/jimfangx/jimfangx/main"
SCRIPT_DIR=""
if [ -f "${BASH_SOURCE[0]:-}" ]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
fi

ZSH_CUSTOM="$HOME/.oh-my-zsh/custom"
CONDA_DIR="$HOME/miniforge3"
SSH_KEY="$HOME/.ssh/id_ed25519"

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
skip() { printf '    already done: %s\n' "$*"; }
warn() { printf '\033[1;33mWARNING: %s\033[0m\n' "$*" >&2; }

clone_once() {
  local url="$1" dir="$2"
  if [ -d "$dir" ]; then
    skip "$dir"
  else
    git clone --depth=1 "$url" "$dir"
  fi
}

# ===  Preflight  ===

missing=()
for cmd in zsh git curl tar ssh-keygen; do
  command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
done
if [ ${#missing[@]} -gt 0 ]; then
  echo "ERROR: missing required commands: ${missing[*]}. Ask an admin to install them." >&2
  exit 1
fi

case "$(uname -m)" in
  x86_64)        NVIM_ARCH="x86_64"; EZA_TARGET="x86_64-unknown-linux-musl" ;;
  aarch64|arm64) NVIM_ARCH="arm64";  EZA_TARGET="aarch64-unknown-linux-gnu" ;;
  *) echo "ERROR: unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
NVIM_DIR="$HOME/nvim-linux-$NVIM_ARCH"

mkdir -p "$HOME/.local/bin" "$HOME/.config"
# Already on PATH in .zshrc. Set here too, so installers below don't add it to shell configs
export PATH="$HOME/.local/bin:$PATH"

# ===  Git  ===

log "Git identity"
git config --global user.name "Jim Fang"
git config --global user.email "yf328@berkeley.edu"

# ===  SSH key  ===

log "SSH key"
mkdir -p "$HOME/.ssh"
chmod 700 "$HOME/.ssh"
if [ -f "$SSH_KEY" ]; then
  skip "$SSH_KEY exists"
  [ -f "$SSH_KEY.pub" ] || ssh-keygen -y -f "$SSH_KEY" > "$SSH_KEY.pub"
else
  ssh-keygen -t ed25519 -N "" -C "$(id -un)@$(hostname)" -f "$SSH_KEY" -q
fi
touch "$HOME/.ssh/authorized_keys"
chmod 600 "$HOME/.ssh/authorized_keys"
if grep -qxF "$(cat "$SSH_KEY.pub")" "$HOME/.ssh/authorized_keys"; then
  skip "public key in authorized_keys"
else
  cat "$SSH_KEY.pub" >> "$HOME/.ssh/authorized_keys"
fi

# ===  .bashrc: run for non-interactive shells too  ===

log "Comment out non-interactive guard in .bashrc"
touch "$HOME/.bashrc"
bashrc_new="$(mktemp)"
awk '
  /^# If not running interactively, don.t do anything$/ { guard = 1; print; next }
  guard && /^case \$- in$/ { block = 1 }
  block { print "#" $0; if ($0 ~ /^esac$/) { block = 0; guard = 0 }; next }
  { guard = 0; print }
' "$HOME/.bashrc" > "$bashrc_new"
if cmp -s "$HOME/.bashrc" "$bashrc_new"; then
  skip "no active guard"
  rm -f "$bashrc_new"
else
  cp "$HOME/.bashrc" "$HOME/.bashrc.pre-bootstrap"
  mv "$bashrc_new" "$HOME/.bashrc"
fi

# ===  Oh My Zsh, Powerlevel10k, plugins  ===

log "Oh My Zsh"
if [ -d "$HOME/.oh-my-zsh" ]; then
  skip "$HOME/.oh-my-zsh"
else
  KEEP_ZSHRC=yes sh -c "$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)" "" --unattended
fi

log "Powerlevel10k"
clone_once https://github.com/romkatv/powerlevel10k.git "$ZSH_CUSTOM/themes/powerlevel10k"
if [ -f "$HOME/.p10k.zsh" ]; then
  skip "$HOME/.p10k.zsh"
elif [ -n "$SCRIPT_DIR" ] && [ -f "$SCRIPT_DIR/.p10k.zsh" ]; then
  cp "$SCRIPT_DIR/.p10k.zsh" "$HOME/.p10k.zsh"
elif ! curl -fsSL -o "$HOME/.p10k.zsh" "$REPO_RAW/.p10k.zsh"; then
  rm -f "$HOME/.p10k.zsh"
  warn "Cannot get .p10k.zsh, p10k configuration wizard will run on first zsh start"
fi

log "zsh-autosuggestions, zsh-syntax-highlighting"
clone_once https://github.com/zsh-users/zsh-autosuggestions "$ZSH_CUSTOM/plugins/zsh-autosuggestions"
clone_once https://github.com/zsh-users/zsh-syntax-highlighting.git "$ZSH_CUSTOM/plugins/zsh-syntax-highlighting"

# ===  .zshrc  ===

ZSHRC_MARKER="# Generated by linux-bootstrap.sh"

log ".zshrc"
if grep -qF "$ZSHRC_MARKER" "$HOME/.zshrc" 2>/dev/null; then
  skip "$HOME/.zshrc"
else
  if [ -f "$HOME/.zshrc" ]; then
    cp "$HOME/.zshrc" "$HOME/.zshrc.pre-bootstrap"
    echo "    existing .zshrc backed up to ~/.zshrc.pre-bootstrap"
  fi
  cat > "$HOME/.zshrc" <<'EOF'
# Generated by linux-bootstrap.sh (github.com/jimfangx/jimfangx)

# Enable Powerlevel10k instant prompt. Should stay close to the top of ~/.zshrc.
# Initialization code that may require console input (password prompts, [y/n]
# confirmations, etc.) must go above this block; everything else may go below.
if [[ -r "${XDG_CACHE_HOME:-$HOME/.cache}/p10k-instant-prompt-${(%):-%n}.zsh" ]]; then
  source "${XDG_CACHE_HOME:-$HOME/.cache}/p10k-instant-prompt-${(%):-%n}.zsh"
fi

export PATH="$HOME/.local/bin:$PATH"

# Path to your oh-my-zsh installation.
export ZSH="$HOME/.oh-my-zsh"
ZSH_THEME="powerlevel10k/powerlevel10k"
plugins=(git zsh-autosuggestions zsh-syntax-highlighting)
source $ZSH/oh-my-zsh.sh

# fzf (installed without completion and key bindings)
[ -f ~/.fzf.zsh ] && source ~/.fzf.zsh

# eza
# Eza colors
export EZA_COLORS='di=1;34:ln=1;36:ex=1;32:*.log=90:*.md=38;5;121:oc=38;5;214'

# Basic listings
alias ls='eza --icons=auto --color=auto --group-directories-first'
alias l='eza --long --all --group --header --octal-permissions --icons=auto --color=auto --time-style=long-iso'

# Sorting (always show hidden files)
alias lsize='l --sort=size --reverse'
alias ltime='l --sort=modified --reverse'
alias lname='l --sort=name'
alias lalpha='l --sort=name'

# Additional conveniences
alias tree='eza --tree --level=2 --icons=auto --color=auto'
alias gsl='l --git'
alias lsg='l --git'

# Git aliases
alias gs='git status'
alias ga='git add .'
alias gc='git commit -m'
alias gm='git commit -m'
alias gp='git push'

# neovim
alias vim="__NVIM_BIN__"
alias vi="__NVIM_BIN__"

# zsh-autosuggestions bind autocomplete to ctrl + 2
bindkey '^@' autosuggest-accept
# don't break autosuggestions
bindkey '^I' expand-or-complete

ZSH_AUTOSUGGEST_STRATEGY=(history completion)


# Define fzf-powered history search
fzf-history-widget() {
  # show commands from history, unique, newest first
  local selected
  selected=$(fc -rl 1 | awk '{$1=""; print substr($0,2)}' | awk '!seen[$0]++' | \
             fzf --height=40% --border --ansi --prompt='History> ')
  if [[ -n $selected ]]; then
    LBUFFER=$selected
  fi
  zle redisplay
}
zle -N fzf-history-widget

# Bind Up arrow to trigger fzf-history-widget
bindkey -r '^[OA'
bindkey '^[OA' fzf-history-widget

# To customize prompt, run `p10k configure` or edit ~/.p10k.zsh.
[[ ! -f ~/.p10k.zsh ]] || source ~/.p10k.zsh

EOF
  sed -i "s|__NVIM_BIN__|$NVIM_DIR/bin/nvim|g" "$HOME/.zshrc"
fi

# ===  fzf  ===

log "fzf"
if [ -d "$HOME/.fzf" ]; then
  skip "$HOME/.fzf"
else
  git clone --depth 1 https://github.com/junegunn/fzf.git "$HOME/.fzf"
  # Same as answering "n" to auto-completion and key bindings, "y" to updating shell configs
  "$HOME/.fzf/install" --no-completion --no-key-bindings --update-rc --no-fish
fi

# ===  eza  ===

log "eza"
if [ -x "$HOME/.local/bin/eza" ]; then
  skip "$HOME/.local/bin/eza"
else
  curl -fsSL "https://github.com/eza-community/eza/releases/latest/download/eza_$EZA_TARGET.tar.gz" \
    | tar -xz -C "$HOME/.local/bin"
fi

# ===  Neovim, NvChad  ===

log "Neovim"
if [ -x "$NVIM_DIR/bin/nvim" ]; then
  skip "$NVIM_DIR"
else
  curl -fsSL "https://github.com/neovim/neovim/releases/latest/download/nvim-linux-$NVIM_ARCH.tar.gz" \
    | tar -xz -C "$HOME"
fi

log "NvChad"
if [ -d "$HOME/.config/nvim" ]; then
  skip "$HOME/.config/nvim"
else
  git clone https://github.com/NvChad/starter "$HOME/.config/nvim"
  rm -rf "$HOME/.config/nvim/.git"
fi
NVIM_OPTIONS="$HOME/.config/nvim/lua/options.lua"
if [ ! -f "$NVIM_OPTIONS" ]; then
  warn "$NVIM_OPTIONS not found (not an NvChad config?), not setting OSC 52 clipboard"
elif grep -qF "vim.g.clipboard = 'osc52'" "$NVIM_OPTIONS"; then
  skip "OSC 52 clipboard"
else
  printf "\nvim.g.clipboard = 'osc52'\n" >> "$NVIM_OPTIONS"
fi
# Install plugins now, instead of on first start
timeout 600 "$NVIM_DIR/bin/nvim" --headless "+Lazy! sync" +qa >/dev/null 2>&1 \
  || warn "NvChad plugin install failed, it will retry on first nvim start"

# ===  Miniforge  ===

log "Miniforge"
if [ -x "$CONDA_DIR/bin/conda" ]; then
  skip "$CONDA_DIR"
else
  installer="$(mktemp -d)/miniforge.sh"
  curl -fsSL -o "$installer" \
    "https://github.com/conda-forge/miniforge/releases/latest/download/Miniforge3-$(uname)-$(uname -m).sh"
  bash "$installer" -b -p "$CONDA_DIR"
  rm -rf "$(dirname "$installer")"
fi
"$CONDA_DIR/bin/conda" init zsh
# Activate base env in new shells ("auto_activate_base" before conda 25.5)
"$CONDA_DIR/bin/conda" config --set auto_activate true 2>/dev/null \
  || "$CONDA_DIR/bin/conda" config --set auto_activate_base true

# ===  tmux  ===

log "tmux-config"
if ! command -v tmux >/dev/null 2>&1; then
  warn "tmux not found, skipping tmux-config. Ask an admin to install tmux, then re-run"
else
  if [ -d "$HOME/tmux-config" ]; then
    skip "clone at ~/tmux-config"
  else
    git clone https://github.com/jimfangx/tmux-config "$HOME/tmux-config"
  fi
  # install.sh pulls in updates itself when re-run
  bash "$HOME/tmux-config/install.sh"
fi

# ===  Codex, Claude Code  ===

log "Codex"
if [ -x "$HOME/.local/bin/codex" ]; then
  skip "$HOME/.local/bin/codex (updates itself)"
else
  # Non-interactive: don't ask "Start Codex now?" at the end
  curl -fsSL https://chatgpt.com/codex/install.sh | CODEX_NON_INTERACTIVE=1 sh
fi

log "Claude Code"
if [ -x "$HOME/.local/bin/claude" ]; then
  skip "$HOME/.local/bin/claude (updates itself)"
else
  curl -fsSL https://claude.ai/install.sh | bash
fi

# ===  Default shell  ===

log "Default shell"
zsh_path="$(command -v zsh)"
login_shell="$(getent passwd "$(id -un)" | cut -d: -f7 || true)"
if [ "$(basename "${login_shell:-}")" = "zsh" ]; then
  skip "login shell is $login_shell"
elif chsh -s "$zsh_path" </dev/null; then
  echo "    login shell changed to $zsh_path"
elif grep -qF "# >>> linux-bootstrap zsh >>>" "$HOME/.bashrc"; then
  skip "zsh is started from .bashrc"
else
  # chsh needs the account password (or sudo), so start zsh from bash instead
  echo "    chsh failed, starting zsh from .bashrc instead"
  cat >> "$HOME/.bashrc" <<'EOF'

# >>> linux-bootstrap zsh >>>
# Login shell can't be changed without password/sudo, so switch to zsh for interactive
# shells, but not `bash -ic "cmd"` (e.g. VS Code remote reads env this way).
# SHELL is updated, so tmux etc. start zsh too. Running `bash` from zsh still works
if [[ $- == *i* ]] && [ -z "${BASH_EXECUTION_STRING:-}" ] && [ -z "${BOOTSTRAP_ZSH:-}" ] \
    && command -v zsh >/dev/null 2>&1; then
  export BOOTSTRAP_ZSH=1
  export SHELL="$(command -v zsh)"
  exec zsh
fi
# <<< linux-bootstrap zsh <<<
EOF
fi

# ===  Done  ===

log "Done. Open a new terminal (or run: exec zsh) to start using it"
echo "    For p10k icons, use a Nerd Font in your terminal (e.g. MesloLGS NF)"
echo
echo "Public key ($SSH_KEY.pub):"
cat "$SSH_KEY.pub"
